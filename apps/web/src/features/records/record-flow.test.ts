// @vitest-environment node
import { beforeAll, beforeEach, expect, it, vi } from 'vitest'
import { claims, evidencePackFor, evidenceVersions, inShop, issueRenterLink, renterLinks, reserveEvidencePack, staffRoles } from '@hold/db'
import { tampered } from '@/test/tampered'
process.env['HOLD_ENVIRONMENT'] = 'test'
process.env['HOLD_COOKIE_KEY'] = Buffer.alloc(32, 21).toString('base64')
const jar = new Map<string, string>()
vi.mock('next/headers', () => ({ cookies: () => Promise.resolve({ get: (name: string) => jar.has(name) ? { name, value: jar.get(name) } : undefined, set: (name: string, value: string) => jar.set(name, value), delete: (cookie: string | { name: string }) => jar.delete(typeof cookie === 'string' ? cookie : cookie.name) }), headers: () => Promise.resolve(new Headers()) }))
vi.mock('next/cache', () => ({ revalidatePath: () => undefined }))
vi.mock('next-intl/server', () => ({ getTranslations: () => Promise.resolve((key: string) => key) }))
const { getServices } = await import('@/server/services')
const { form, signIn } = await import('@/test/shop-session')
const { handoverShop } = await import('@/test/ready-rental')
const owner = 'owner@record-flow.example'
let shop: Awaited<ReturnType<typeof handoverShop>>
let rental: { rentalId: string; token: string }
beforeAll(async () => { shop = await handoverShop(jar, owner, 'Record Bikes'); rental = await shop.readyRental() })
beforeEach(() => { jar.clear() })
it('builds through authenticated actions and downloads the frozen PDF and manifest as staff and renter', async () => {
  const { buildRecord, downloadRecord } = await import('./actions')
  const { downloadRenterRecord } = await import('./renter-actions')
  expect(await buildRecord(null, form({ rentalId: rental.rentalId, locale: 'en' }))).toMatchObject({ ok: false, failure: 'signed_out' })
  await signIn(jar, owner, 'email_code')
  const requested = await buildRecord(null, form({ rentalId: rental.rentalId, locale: 'en' }))
  if (!requested.ok) throw new Error(JSON.stringify(requested))
  const packId = requested.value.packId
  const { database } = await getServices()
  expect(await inShop(database, { role: 'hold_app', shopId: shop.shopId }, (transaction) => evidencePackFor(transaction, rental.rentalId, packId))).toMatchObject({ state: 'ready' })
  const pdf = await downloadRecord(null, form({ rentalId: rental.rentalId, packId, kind: 'pdf', locale: 'en' }))
  expect(pdf).toMatchObject({ ok: true, value: { filename: 'rental-record-v1.pdf' } })
  if (pdf.ok) expect(Buffer.from(pdf.value.url.split(',')[1] ?? '', 'base64').subarray(0, 5).toString()).toBe('%PDF-')
  jar.clear()
  const manifest = await downloadRenterRecord(null, form({ token: rental.token, packId, kind: 'manifest', locale: 'en' }))
  expect(manifest).toMatchObject({ ok: true, value: { filename: 'rental-manifest-v1.json' } })
  if (manifest.ok) expect(Buffer.from(manifest.value.url.split(',')[1] ?? '', 'base64').toString()).not.toContain('evidenceKey')
  expect(await downloadRenterRecord(null, form({ token: rental.token, packId, kind: 'pdf', amountCents: '1', locale: 'en' }))).toMatchObject({ ok: false, failure: 'invalid' })
})
it('denies a valid token for another rental, forged, revoked and expired links', async () => {
  const { buildRecord } = await import('./actions')
  const { downloadRenterRecord } = await import('./renter-actions')
  const other = await shop.readyRental()
  await signIn(jar, owner, 'email_code')
  const requested = await buildRecord(null, form({ rentalId: other.rentalId, locale: 'en' }))
  if (!requested.ok) throw new Error(JSON.stringify(requested))
  const fields = { token: rental.token, packId: requested.value.packId, kind: 'pdf', locale: 'en' }
  expect(await downloadRenterRecord(null, form(fields))).toMatchObject({ ok: false })
  expect(await downloadRenterRecord(null, form({ ...fields, token: tampered(rental.token) }))).toMatchObject({ ok: false, failure: 'link_invalid' })
  const { database } = await getServices()
  await inShop(database, { role: 'hold_app', shopId: shop.shopId }, (transaction) => transaction.update(renterLinks).set({ expiresAt: new Date('2020-01-01') }))
  expect(await downloadRenterRecord(null, form({ ...fields, token: other.token }))).toMatchObject({ ok: false, failure: 'link_invalid' })
  const { newRenterLink } = await import('@/server/renter-links')
  const fresh = await newRenterLink(new Date())
  await inShop(database, { role: 'hold_app', shopId: shop.shopId }, (transaction) => issueRenterLink(transaction, shop.shopId, rental.rentalId, fresh, ['view']))
  await inShop(database, { role: 'hold_app', shopId: shop.shopId }, (transaction) => transaction.update(renterLinks).set({ revokedAt: new Date() }))
  expect(await downloadRenterRecord(null, form({ ...fields, token: fresh.token }))).toMatchObject({ ok: false, failure: 'link_invalid' })
})

it('denies missing scope, another shop, unapproved claim packs and read-only build requests', async () => {
  const { buildRecord, downloadRecord } = await import('./actions')
  const { downloadRenterRecord } = await import('./renter-actions')
  const current = await shop.readyRental()
  await signIn(jar, owner, 'email_code')
  const requested = await buildRecord(null, form({ rentalId: current.rentalId, locale: 'en' }))
  if (!requested.ok) throw new Error(JSON.stringify(requested))
  const { database, flushRecords } = await getServices()
  const { newRenterLink } = await import('@/server/renter-links')
  const limited = await newRenterLink(new Date())
  await inShop(database, { role: 'hold_app', shopId: shop.shopId }, (transaction) => issueRenterLink(transaction, shop.shopId, current.rentalId, limited, []))
  expect(await downloadRenterRecord(null, form({ token: limited.token, packId: requested.value.packId, kind: 'pdf', locale: 'en' }))).toMatchObject({ ok: false, failure: 'scope' })
  const draft = await inShop(database, { role: 'hold_app', shopId: shop.shopId }, async (transaction) => {
    await transaction.insert(claims).values({ shopId: shop.shopId, rentalId: current.rentalId, currency: 'EUR', totalCents: 3500, state: 'awaiting_approval' })
    return reserveEvidencePack(transaction, current.rentalId, new Date())
  })
  await flushRecords(shop.shopId)
  expect(await downloadRenterRecord(null, form({ token: current.token, packId: draft?.id ?? '', kind: 'pdf', locale: 'en' }))).toMatchObject({ ok: false })
  expect(await inShop(database, { role: 'hold_app', shopId: shop.shopId }, (transaction) => evidenceVersions(transaction, current.rentalId, true))).not.toEqual(expect.arrayContaining([expect.objectContaining({ id: draft?.id })]))
  await inShop(database, { role: 'hold_app', shopId: shop.shopId }, (transaction) => transaction.update(staffRoles).set({ role: 'read_only' }))
  expect(await buildRecord(null, form({ rentalId: current.rentalId, locale: 'en' }))).toMatchObject({ ok: false, failure: 'role' })
  expect(await downloadRecord(null, form({ rentalId: current.rentalId, packId: requested.value.packId, kind: 'pdf', locale: 'en' }))).toMatchObject({ ok: true })
  await inShop(database, { role: 'hold_app', shopId: shop.shopId }, (transaction) => transaction.update(staffRoles).set({ role: 'owner' }))
  await handoverShop(jar, 'other-owner@record-flow.example', 'Other Record Bikes')
  expect(await downloadRecord(null, form({ rentalId: current.rentalId, packId: requested.value.packId, kind: 'pdf', locale: 'en' }))).toMatchObject({ ok: false })
})
